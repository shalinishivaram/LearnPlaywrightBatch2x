// LOGICAL Operators are used to combine or invert boolean values. 
// They are often used in conditional statements to control the flow of a program based on multiple conditions. Here are the main logical operators in JavaScript:

// Logical Operators
let a = true;
let b = false;  
console.log(a && b); // Logical AND: false (true only if both operands are true)
console.log(a || b); // Logical OR: true (true if at least one operand is true)
console.log(!b); // Logical NOT: true (inverts the boolean value)      