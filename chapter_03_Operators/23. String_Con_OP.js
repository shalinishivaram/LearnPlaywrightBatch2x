// String Concatenation Operators are used to combine two or more strings into a single string. In JavaScript, 
// the primary operator for string concatenation is the plus (+) operator. Here's how it works:

// String Concatenation Operators
let str1 = "Hello, ";
let str2 = "World!";
let result = str1 + str2;
console.log(result); // Output: Hello, World!

// You can also use the += operator to concatenate strings and assign the result to the same variable:
let str3 = "Hello, ";
str3 += "JavaScript!";
console.log(str3); // Output: Hello, JavaScript!

