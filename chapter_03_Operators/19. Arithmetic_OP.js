// arithmetic operators are used to perform mathematical operations on numbers. Here are the basic arithmetic operators in JavaScript:
// Arithithmetic Operators
let a = 10;
let b = 5;
console.log(a + b); // Addition: 15
console.log(a - b); // Subtraction: 5
console.log(a * b); // Multiplication: 50
console.log(a / b); // Division: 2
console.log(a % b); // Modulus: 0. modulus returns the remainder of a division operation. It is used to determine if a number is even or odd, to wrap around values within a certain range, and to perform cyclic operations.
console.log(a ** b); // Exponentiation: 100000
